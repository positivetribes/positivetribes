// Builds src/playbook-data.js, the command center's Playbook tab (#/command/playbook), from the commands and kits themselves:
// each Claude Code command in ~/.claude/skills/<name>/SKILL.md (name, description, argument-hint) and each kit in
// ../kits (its README's title and first paragraph). Only names and one-line descriptions are copied: this repo is public,
// so the commands' full instructions stay in ~/.claude. Runs before every deploy (npm run deploy); npm run playbook runs it alone.
import { readFileSync, readdirSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const MAX = 320;
const clip = s => s.length > MAX ? s.slice(0, MAX - 1).trimEnd() + '…' : s;

// The YAML-ish front matter Claude Code skills use: one "key: value" per line between --- fences.
export function frontMatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const out = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (kv) out[kv[1]] = kv[2].replace(/^(["'])(.*)\1$/, '$2').trim();
  }
  return out;
}

// A kit's title (first "# " line) and summary (first paragraph after it), as plain text.
export function kitSummary(text) {
  const lines = text.split(/\r?\n/);
  const at = lines.findIndex(l => /^#\s+/.test(l));
  const title = at >= 0 ? lines[at].replace(/^#\s+/, '').trim() : '';
  const para = [];
  for (const l of lines.slice(at + 1)) {
    if (!l.trim()) { if (para.length) break; continue; }
    if (/^(#|```|\||- |\d+\. )/.test(l)) { if (para.length) break; continue; }
    para.push(l.trim());
  }
  const summary = para.join(' ').replace(/\*\*|`/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
  return { title, summary: clip(summary) };
}

export function buildPlaybook({ skillsDir, kitsDir }) {
  const commands = readdirSync(skillsDir).sort()
    .map(name => join(skillsDir, name, 'SKILL.md'))
    .filter(existsSync)
    .map(file => frontMatter(readFileSync(file, 'utf8')))
    .filter(f => f.name && f.description && f['user-invocable'] !== 'false')
    .map(f => ({ name: f.name, args: f['argument-hint'] || '', description: clip(f.description) }));
  const kits = readdirSync(kitsDir).sort().flatMap(entry => {
    const full = join(kitsDir, entry);
    const file = statSync(full).isDirectory() ? join(full, 'README.md') : entry.endsWith('.md') ? full : null;
    if (!file || !existsSync(file)) return [];
    const { title, summary } = kitSummary(readFileSync(file, 'utf8'));
    return title ? [{ title, summary, path: 'kits/' + entry + (statSync(full).isDirectory() ? '/' : '') }] : [];
  });
  return { commands, kits };
}

export const render = data => `// Generated by scripts/playbook.mjs from ~/.claude/skills and ../kits. Do not edit by hand: run npm run playbook.\nexport const PLAYBOOK = ${JSON.stringify(data, null, 2)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  const skillsDir = process.env.PLAYBOOK_SKILLS || join(homedir(), '.claude', 'skills');
  const out = join(here, '..', 'src', 'playbook-data.js');
  // Off Eric's Mac (no skills folder) keep the committed file rather than publish an empty list.
  if (!existsSync(skillsDir)) { console.log(`playbook: ${skillsDir} not found, keeping src/playbook-data.js as it is`); process.exit(0); }
  const text = render(buildPlaybook({ skillsDir, kitsDir: join(here, '..', '..', 'kits') }));
  const before = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (text === before) console.log('playbook: up to date');
  else { writeFileSync(out, text); console.log('playbook: src/playbook-data.js updated, commit it'); }
}
